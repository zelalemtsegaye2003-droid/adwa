/**
 * Adwa Cyber — Track C gate evidence & timeline seeder (accountability layer).
 *
 * Idempotent:
 *  1. Backfills a CRITERION_SEEDED GateEvent for every criterion that has no
 *     events yet, so no timeline is empty.
 *  2. DEDICATED_FUNDING (the criterion the board demo advanced to SATISFIED)
 *     gets a clearly-labelled fixture artefact + a matching STATUS_CHANGE
 *     event, keeping the recorded state consistent with the new server-side
 *     rule (SATISFIED requires ≥1 artefact).
 *
 * The fixture is explicitly marked as a seed artefact — it stands in for the
 * signed institutional funding letter and must be replaced before any real
 * gate review. Never fabricates instruments for the other criteria.
 *
 * Usage: npx tsx scripts/seed-gate-evidence.ts
 */
import { PrismaClient } from "@prisma/client";
import { createHash, randomBytes } from "crypto";
import fs from "fs";
import path from "path";
import { assertSeedAllowed } from "./seed-guard";

const db = new PrismaClient();

// D6 guard — refuses to seed a production DB without explicit opt-in
assertSeedAllowed("demo");
const STORAGE_ROOT = path.join(process.cwd(), ".data", "gate-evidence");

const FIXTURE_BODY = `ADWA CYBER — TRACK C GATE EVIDENCE (SEED FIXTURE)
=================================================

Criterion : P4_ACFS / DEDICATED_FUNDING
Artefact  : Institutional funding commitment (placeholder)

This file is a SEED FIXTURE generated by scripts/seed-gate-evidence.ts.
It stands in for the signed institutional funding commitment letter
(roadmap: the filtering programme is funded from dedicated institutional
funding, never from Track A commercial revenue).

Replace this artefact with the signed instrument before any real gate
review, funder due diligence, or regulator inspection.

Sealed at upload with SHA-256; downloads re-verify the checksum.
Generated: ${new Date().toISOString()}
`;

(async () => {
  let seededEvents = 0;
  let seededEvidence = 0;

  const gates = await db.expansionGate.findMany({ orderBy: [{ phase: "asc" }, { code: "asc" }] });
  const superAdmin = await db.user.findFirst({ where: { role: "SUPER_ADMIN" }, select: { id: true, name: true } });
  if (!superAdmin) throw new Error("SUPER_ADMIN user not found — cannot attribute gate evidence.");

  for (const g of gates) {
    const count = await db.gateEvent.count({ where: { gateId: g.id } });
    if (count === 0) {
      await db.gateEvent.create({
        data: {
          gateId: g.id,
          actorId: null, // seeder, not a person
          kind: "CRITERION_SEEDED",
          note: `Criterion defined from the roadmap (§3.2 Table 2) — ${g.phase}/${g.code}.`,
        },
      });
      seededEvents++;
    }
  }

  // DEDICATED_FUNDING fixture artefact + status-change backfill
  const funding = gates.find((g) => g.phase === "P4_ACFS" && g.code === "DEDICATED_FUNDING");
  if (funding) {
    const hasEvidence = await db.gateEvidence.count({ where: { gateId: funding.id } }) > 0;
    if (!hasEvidence) {
      const bytes = Buffer.from(FIXTURE_BODY, "utf8");
      const storedName = randomBytes(16).toString("hex") + ".txt";
      fs.mkdirSync(STORAGE_ROOT, { recursive: true });
      fs.writeFileSync(path.join(STORAGE_ROOT, storedName), bytes, { mode: 0o600 });

      const doc = await db.gateEvidence.create({
        data: {
          gateId: funding.id,
          fileName: "seed-fixture-institutional-funding-commitment.txt",
          storedName,
          mimeType: "text/plain",
          fileSize: bytes.length,
          checksum: createHash("sha256").update(bytes).digest("hex"),
          description: "Seed fixture — replace with the signed institutional funding letter before any gate review.",
          uploadedById: superAdmin.id,
        },
      });
      seededEvidence++;

      await db.gateEvent.create({
        data: {
          gateId: funding.id,
          actorId: superAdmin.id,
          kind: "EVIDENCE_ATTACHED",
          evidenceId: doc.id,
          note: `${doc.fileName} — seed fixture standing in for the signed funding letter.`,
        },
      });

      // Backfill the recorded status history (the criterion is already
      // SATISFIED from the board demo) so the timeline reads coherently.
      const hasStatusChange = await db.gateEvent.count({
        where: { gateId: funding.id, kind: "STATUS_CHANGE" },
      }) > 0;
      if (!hasStatusChange && funding.status === "SATISFIED") {
        await db.gateEvent.create({
          data: {
            gateId: funding.id,
            actorId: superAdmin.id,
            kind: "STATUS_CHANGE",
            fromStatus: "NOT_STARTED",
            toStatus: "SATISFIED",
            note: funding.notes ?? "Institutional grant committed for the filtering programme.",
          },
        });
      }
    }
  }

  const totals = await Promise.all([
    db.gateEvent.count(),
    db.gateEvidence.count(),
  ]);
  console.log(
    `Track C accountability seed: ${seededEvents} seeded-event(s) backfilled, ${seededEvidence} fixture artefact(s) attached. Totals — ${totals[0]} events, ${totals[1]} evidence artefacts.`
  );
  await db.$disconnect();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
