// ── Canonical content hash (payload-level, verifiable) ──────────────────────

/**
 * Deterministic SHA-256 over the report *numbers* — org, framework, scores,
 * every finding with its SLA state — so a supervisor can independently
 * recompute it from the API payload. (Hashing the PDF bytes would be
 * meaningless: creation timestamps change them.)
 */
export function reportContentHash(scan: ReportScanLite): string {
  const payload = {
    org: scan.organization.name,
    scan: scan.name,
    framework: scan.framework?.code ?? null,
    completedAt: scan.completedAt?.toISOString() ?? null,
    overallScore: scan.overallScore,
    pillars: scan.pillarScores ? JSON.parse(scan.pillarScores) : null,
    findings: scan.results
      .filter((r) => r.answer === "no" || r.answer === "partial")
      .sort((a, b) => a.rule.code.localeCompare(b.rule.code))
      .map((r) => ({
        code: r.rule.code,
        answer: r.answer,
        status: r.status,
        riskRank: r.riskRank,
        dueAt: r.dueAt?.toISOString() ?? null,
        remediatedAt: r.remediatedAt?.toISOString() ?? null,
      })),
  };
  return createHash("sha256").update(JSON.stringify(payload)).digest("hex").slice(0, 16);
}

