export function generateReportPdf(scan: ReportScanLite, lang: ReportLang = "en"): Promise<GeneratedReport> {
  return new Promise((resolve, reject) => {
    const t = (k: string) => {
      const e = S[k];
      return e ? (lang === "en" ? e[0] : e[1]) : k;
    };
    const pick = (en: string, am: string) => (lang === "en" ? en : am);

    const doc = new PDFDocument({
      size: "A4",
      bufferPages: true, // keep pages editable until end() so footers can be stamped
      margins: { top: 56, bottom: 64, left: 48, right: 48 },
      info: {
        Title: `${t("reportTitle")} — ${scan.organization.name}`,
        Author: "Adwa Cyber Compliance Platform",
        Subject: `${scan.framework?.name ?? "Compliance"} · ${scan.name}`,
        Creator: "Adwa Cyber Compliance Engine",
      },
    });

    const W = doc.page.width;
    const H = doc.page.height;
    const M = doc.page.margins;
    const CW = W - M.left - M.right;

    try {
      const findings = scan.results.filter((r) => r.answer === "no" || r.answer === "partial");
      const severityCounts = { critical: 0, high: 0, medium: 0 };
      for (const f of findings) severityCounts[f.rule.severity as keyof typeof severityCounts]++;
      const statusCounts = { open: 0, in_progress: 0, remediated: 0, waived: 0 };
      for (const f of findings) statusCounts[f.status as keyof typeof statusCounts]++;
      const pillarScores: Record<string, number> = scan.pillarScores ? JSON.parse(scan.pillarScores) : {};

      // ── 1. Header band ──────────────────────────────────────────────────
      doc.rect(0, 0, W, 8).fill(C.brand);

      doc.fontSize(10).fillColor(C.muted).font(F.latin.regular);
      mixedText(doc, `${t("reportTitle")} · ${scan.framework?.code ?? "PD-1321"}`, F.latin, F.ethiopic);
      doc.moveDown(0.4);
      doc.fontSize(20).fillColor(C.ink);
      mixedText(doc, pick(scan.organization.name, scan.organization.nameAm || scan.organization.name), F.latin, F.ethiopic, { bold: true });
      doc.moveDown(0.25);
      doc.fontSize(11).fillColor(C.muted);
      mixedText(doc, `${scan.name} · ${scan.framework?.instrumentNo ?? ""}`, F.latin, F.ethiopic);
      doc.moveDown(0.35);
      doc.fontSize(9.5);
      const completedStr = scan.completedAt ? new Date(scan.completedAt).toISOString().slice(0, 10) : "—";
      mixedText(
        doc,
        `${t("auditor")}: ${scan.auditorName ?? "Adwa Compliance Engine"} · ${t("completedOn")}: ${completedStr}`,
        F.latin,
        F.ethiopic
      );

      // score ring (top-right)
      const ringX = W - M.right - 104;
      const ringY = M.top + 2;
      const score = scan.overallScore ?? 0;
      doc.save();
      doc.circle(ringX + 52, ringY + 52, 46).lineWidth(9).strokeColor(C.line).stroke();
      const frac = Math.max(0, Math.min(100, score)) / 100;
      arcOf(doc)
        .moveTo(ringX + 52, ringY + 6)
        .arc(ringX + 52, ringY + 52, 46, -Math.PI / 2, -Math.PI / 2 + frac * 2 * Math.PI)
        .lineWidth(9)
        .strokeColor(scoreColorHex(score))
        .stroke();
      doc.restore();
      doc.font(F.latin.bold).fontSize(26).fillColor(scoreColorHex(score)).text(String(score), ringX + 12, ringY + 36, { width: 80, align: "center", lineBreak: false });
      doc.font(F.latin.regular).fontSize(8).fillColor(C.muted).text("%", ringX + 12, ringY + 66, { width: 80, align: "center", lineBreak: false });

      doc.y = Math.max(doc.y, ringY + 112) + 12;
      doc.moveTo(M.left, doc.y).lineTo(W - M.right, doc.y).lineWidth(1).strokeColor(C.line).stroke();
      doc.y += 16;

      // ── 2. Pillars (left) + findings donut (right) ──────────────────────
      const colGap = 18;
      const colW = (CW - colGap) / 2;
      const topY = doc.y;

      doc.fontSize(12.5).fillColor(C.ink);
      mixedText(doc, t("pillarPerf"), F.latin, F.ethiopic, { bold: true });
      doc.y += 10;
      const entries = Object.entries(pillarScores);
      const pillarStartY = doc.y; // anchor: label() calls advance doc.y, so rows must be positioned from a captured start
      const barW = colW - 130;
      entries.forEach(([pillar, sc], i) => {
        const y = pillarStartY + i * 21;
        const pl = pillar.length > 19 ? pillar.slice(0, 18) + "…" : pillar;
        label(doc, pl, M.left, y, { bold: false, size: 9.5, color: C.ink, lineBreak: false });
        doc.rect(M.left + 118, y + 1, barW, 8).fill(C.line);
        doc.rect(M.left + 118, y + 1, (barW * Math.max(0, Math.min(100, sc))) / 100, 8).fill(scoreColorHex(sc));
        doc.font(F.latin.bold).fontSize(9.5).fillColor(scoreColorHex(sc));
        doc.text(`${Math.round(sc)}%`, M.left + 118 + barW + 6, y - 1.5, { lineBreak: false });
      });

      // right column
      const rx = M.left + colW + colGap;
      doc.fontSize(12.5).fillColor(C.ink);
      doc.font(F.latin.bold).text(t("findingsSummary"), rx, topY, { lineBreak: false });
      const dy = topY + 54;
      const total = findings.length || 1;
      let angle = -Math.PI / 2;
      const segs = [
        { n: severityCounts.critical, c: C.red },
        { n: severityCounts.high, c: C.amber },
        { n: severityCounts.medium, c: C.yellow },
      ].filter((s) => s.n > 0);
      if (segs.length === 0) {
        doc.save().circle(rx + 40, dy, 28).lineWidth(12).strokeColor(C.line).stroke().restore();
      } else {
        for (const s of segs) {
          const sweep = (s.n / total) * 2 * Math.PI;
          arcOf(doc)
            .moveTo(rx + 40 + 28 * Math.cos(angle), dy + 28 * Math.sin(angle))
            .arc(rx + 40, dy, 28, angle, angle + sweep)
            .lineWidth(12)
            .strokeColor(s.c)
            .stroke();
          angle += sweep;
        }
      }
      doc.font(F.latin.bold).fontSize(16).fillColor(C.ink).text(String(findings.length), rx + 18, dy - 8, { width: 44, align: "center", lineBreak: false });
      label(doc, t("findings"), rx + 18, dy + 8, { bold: false, size: 7, color: C.muted, width: 44, align: "center", lineBreak: false });
      // legend + status mix
      let ly = dy - 30;
      for (const l of [
        { label: t("critical"), n: severityCounts.critical, c: C.red },
        { label: t("high"), n: severityCounts.high, c: C.amber },
        { label: t("medium"), n: severityCounts.medium, c: C.yellow },
      ]) {
        doc.rect(rx + 92, ly + 3, 7, 7).fill(l.c);
        label(doc, `${l.label}  ${l.n}`, rx + 104, ly, { bold: false, size: 9, color: C.ink, lineBreak: false });
        ly += 15;
      }
      label(
        doc,
        `${statusCounts.remediated} ${t("remediated")} · ${statusCounts.in_progress} ${t("inProgress")} · ${statusCounts.waived} ${t("waived")}`,
        rx + 92,
        ly + 4,
        { width: colW - 96, lineBreak: false }
      );

      doc.y = Math.max(pillarStartY + entries.length * 21 + 6, dy + 46);

      // ── 3. Time comparison strip ────────────────────────────────────────
      doc.rect(M.left, doc.y, CW, 56).fill(C.brandSoft);
      const stripY = doc.y;
      doc.fontSize(12).fillColor(C.brand);
      mixedText(doc, t("timeComparison"), F.latin, F.ethiopic, { bold: true, x: M.left + 14, y: stripY + 8 });
      const mins = scan.durationMinutes ?? 0;
      const reduction = Math.max(0, Math.round((1 - mins / 60 / 40) * 1000) / 10);
      label(doc, `${t("manual")}: 40–80 h`, M.left + 14, stripY + 28, { bold: false, size: 9.5, color: C.ink, lineBreak: false });
      label(doc, `${t("engine")}: ${mins.toFixed(1)} min`, M.left + 170, stripY + 28, { bold: false, size: 9.5, color: C.ink, lineBreak: false });
      doc.font(F.latin.bold).fontSize(14).fillColor(C.brand);
      doc.text(`−${reduction}%`, W - M.right - 140, stripY + 24, { width: 126, align: "right", lineBreak: false });
      label(doc, t("reduction"), W - M.right - 190, stripY + 41, { bold: false, size: 7.5, color: C.muted, width: 176, align: "right", lineBreak: false });
      doc.y = stripY + 56 + 18;

      // ── 4. Article risk bars ────────────────────────────────────────────
      doc.fontSize(12.5).fillColor(C.ink);
      mixedText(doc, t("articleRisk"), F.latin, F.ethiopic, { bold: true });
      doc.y += 10;
      const artMap = new Map<string, { flagged: number; total: number }>();
      for (const r of scan.results) {
        const e = artMap.get(r.rule.article) ?? { flagged: 0, total: 0 };
        e.total++;
        if (r.answer === "no" || r.answer === "partial") e.flagged++;
        artMap.set(r.rule.article, e);
      }
      const arts = [...artMap.entries()]
        .sort((a, b) => b[1].flagged / b[1].total - a[1].flagged / a[1].total)
        .slice(0, 12);
      const artBarW = CW - 210;
      const artStartY = doc.y; // anchor (same reason as pillars)
      arts.forEach(([article, v], i) => {
        const y = artStartY + i * 15;
        const rate = Math.round((v.flagged / v.total) * 100);
        label(doc, article, M.left, y, { bold: false, size: 8.5, color: C.muted, width: 96, lineBreak: false });
        doc.rect(M.left + 102, y + 1, artBarW, 7).fill(C.line);
        doc.rect(M.left + 102, y + 1, (artBarW * rate) / 100, 7).fill(rate >= 75 ? C.red : rate >= 40 ? C.amber : C.green);
        label(doc, `${v.flagged}/${v.total} ${t("flagged")}`, M.left + 102 + artBarW + 8, y, { bold: false, size: 8.5, color: C.ink, lineBreak: false });
      });
      doc.y = artStartY + arts.length * 15 + 20;

      // ── 5. Top remediation priorities with SLA ──────────────────────────
      doc.fontSize(12.5).fillColor(C.ink);
      mixedText(doc, t("topRemediation"), F.latin, F.ethiopic, { bold: true });
      doc.moveDown(0.3);
      doc.fontSize(7.5).fillColor(C.muted);
      mixedText(
        doc,
        `Corrective-action deadlines: critical ${slaDaysFor("critical")}d · high ${slaDaysFor("high")}d · medium ${slaDaysFor("medium")}d (Procl. 1426/2026; due-soon window ${SLA_DUE_SOON_WINDOW_DAYS}d).`,
        F.latin,
        F.ethiopic
      );
      doc.y += 10;

      const plan = [...findings].sort((a, b) => (b.riskRank ?? 0) - (a.riskRank ?? 0)).slice(0, 10);
      const colRule = 250;
      const colSev = 52;
      const colRisk = 40;

      const headY = doc.y;
      doc.rect(M.left, headY, CW, 18).fill(C.headFill);
      label(doc, "#", M.left + 6, headY + 5, { size: 8.5, color: C.ink, lineBreak: false });
      label(doc, t("rule"), M.left + 24, headY + 5, { size: 8.5, color: C.ink, width: colRule, lineBreak: false });
      label(doc, t("critical").slice(0, 3) + ".", M.left + 24 + colRule, headY + 5, { size: 8.5, color: C.ink, width: colSev, lineBreak: false });
      label(doc, t("risk"), M.left + 24 + colRule + colSev, headY + 5, { size: 8.5, color: C.ink, width: colRisk, lineBreak: false });
      label(doc, `${t("slaTitle")} · ${t("slaDue")}`, M.left + 24 + colRule + colSev + colRisk, headY + 5, { size: 8.5, color: C.ink, lineBreak: false });
      doc.y = headY + 18;

      plan.forEach((f, i) => {
        const rowH = 34;
        if (doc.y + rowH > H - M.bottom - 8) doc.addPage();
        const y = doc.y;
        if (i % 2 === 1) doc.rect(M.left, y, CW, rowH).fill(C.zebra);
        doc.font(F.latin.bold).fontSize(9).fillColor(C.ink);
        doc.text(String(i + 1), M.left + 6, y + 4, { lineBreak: false });
        doc.fontSize(8.5);
        doc.text(f.rule.code, M.left + 24, y + 4, { lineBreak: false });
        doc.font(F.latin.regular).fontSize(8);
        const title = pick(f.rule.titleEn, f.rule.titleAm);
        doc.text(title.length > 56 ? title.slice(0, 55) + "…" : title, M.left + 24, y + 15, { width: colRule, lineBreak: false });
        // severity chip
        doc.rect(M.left + 24 + colRule, y + 4, 44, 11).fill(severityColor(f.rule.severity));
        doc.font(F.latin.bold).fontSize(7).fillColor("#FFFFFF");
        doc.text(f.rule.severity.toUpperCase(), M.left + 24 + colRule, y + 6.5, { width: 44, align: "center", lineBreak: false });
        doc.font(F.latin.bold).fontSize(9).fillColor(C.ink);
        doc.text((f.riskRank ?? 0).toFixed(1), M.left + 24 + colRule + colSev, y + 5, { width: colRisk, lineBreak: false });
        // SLA cell
        const sla = slaInfo({ status: f.status, dueAt: f.dueAt, remediatedAt: f.remediatedAt });
        const slaLabel =
          sla.state === "WAIVED" ? t("slaWaived")
          : sla.state === "NOT_TRACKED" ? t("noDeadline")
          : sla.state === "OVERDUE" ? `${t("overdue")} ${Math.abs(sla.daysRemaining ?? 0)}${t("daysOver")}`
          : sla.state === "DUE_SOON" ? `${t("dueSoon")} ${sla.daysRemaining}${t("daysLeft")}`
          : sla.state === "ON_TRACK" ? `${t("onTrack")} ${sla.daysRemaining}${t("daysLeft")}`
          : sla.state === "CLOSED_ON_TIME" ? t("closedOnTime")
          : t("closedLate");
        doc.font(F.latin.bold).fontSize(8).fillColor(slaColor(sla.state));
        const slaText = slaLabel.replace(/(\d+)/, "$1 "); // "OVERDUE 15d over" spacing
        label(doc, slaText, M.left + 24 + colRule + colSev + colRisk, y + 5, { size: 8, color: slaColor(sla.state), lineBreak: false });
        if (sla.dueAt) {
          doc.font(F.latin.regular).fontSize(7.5).fillColor(C.muted);
          doc.text(`due ${new Date(sla.dueAt).toISOString().slice(0, 10)}`, M.left + 24 + colRule + colSev + colRisk, y + 16, { lineBreak: false });
        }
        doc.y = y + rowH;
        doc.moveTo(M.left, doc.y).lineTo(W - M.right, doc.y).lineWidth(0.5).strokeColor(C.line).stroke();
      });
      doc.y += 8;

      // penalty footnote
      doc.font(F.latin.regular).fontSize(7.5).fillColor(C.muted);
      doc.text(
        `${t("penalty")}: ` + plan.slice(0, 3).map((f) => `${f.rule.code} → ${f.rule.penaltyRef}`).join(" · "),
        M.left,
        doc.y,
        { width: CW, ellipsis: true }
      );
      // ── footers on every page (buffered pages) ──────────────────────────
      const hash = reportContentHash(scan);
      // pdfkit 0.20 exposes the buffered page count via _pageBuffer
      // (bufferedPageCount does not exist in this build)
      const pages = pageBufferOf(doc).length;
      for (let i = 0; i < pages; i++) {
        doc.switchToPage(i);
        // The footer lives INSIDE the bottom margin zone — pdfkit's text
        // overflow check (doc.y > page.maxY()) would silently add spurious
        // pages. Shrink the per-page bottom margin while stamping so the
        // footer text is legal, then restore.
        const savedBottom = doc.page.margins.bottom;
        doc.page.margins.bottom = 12;
        const fy = H - 42;
        doc.moveTo(M.left, fy).lineTo(W - M.right, fy).lineWidth(0.5).strokeColor(C.line).stroke();
        doc.font(F.latin.regular).fontSize(7).fillColor(C.muted);
        mixedText(doc, t("footerConfidential"), F.latin, F.ethiopic, { x: M.left, y: fy + 5 });
        doc.text(`${t("reportHash")}: ${hash}`, M.left, fy + 15, { lineBreak: false });
        label(doc, `${t("page")} ${i + 1}/${pages}`, W - M.right - 60, fy + 15, { size: 7, color: C.muted, width: 60, align: "right", lineBreak: false });
        doc.page.margins.bottom = savedBottom;
      }

      const chunks: Buffer[] = [];
      doc.on("data", (c: Buffer) => chunks.push(c));
      doc.on("end", () => {
        resolve({ buffer: Buffer.concat(chunks), hash, pages });
      });
      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
