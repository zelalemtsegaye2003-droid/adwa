/**
 * Adwa Cyber — Executive report PDF generator (server-only).
 *
 * Renders the compliance assessment report as a vector PDF with pdfkit,
 * fully bilingual (English / አማርኛ). Noto Sans covers Latin; Noto Sans
 * Ethiopic covers Amharic — the two script-only fonts are switched per text
 * run by the mixed() helper, so "አማርኛ · 47 obligations" renders correctly.
 *
 * Sections: header (org, framework, score ring), pillar performance,
 * findings summary donut, time comparison, article risk bars, top remediation
 * priorities with SLA deadlines (Procl. 1426/2026), and a footer on every
 * page with page numbers, confidentiality note and a SHA-256 content hash —
 * the hash covers the canonical report payload (not the PDF bytes, which
 * vary by timestamps), so a supervisor can re-verify the numbers.
 */
