// ── Script-aware text rendering ──────────────────────────────────────────────

const ETHIOPIC_RE = /[\u1200-\u137F\u1380-\u139F\u2D80-\u2DDF\uAB00-\uAB2F]/;
function isEthiopic(ch: string) {
  return ETHIOPIC_RE.test(ch);
}

function mixedText(
  doc: PDFKit.PDFDocument,
  text: string,
  latin: { regular: string; bold: string },
  ethiopic: { regular: string; bold: string },
  opts: { bold?: boolean; x?: number; y?: number } = {}
) {
  const pick = opts.bold ? { latin: latin.bold, eth: ethiopic.bold } : { latin: latin.regular, eth: ethiopic.regular };
  // pdfkit keeps a sticky doc.x after explicit-coordinate calls — always
  // anchor implicit flows at the left margin unless told otherwise
  doc.x = opts.x ?? doc.page.margins.left;
  if (opts.y !== undefined) doc.y = opts.y;
  // split into runs of same-script characters (whitespace joins the previous run)
  const runs: Array<{ eth: boolean; s: string }> = [];
  for (const ch of text) {
    const eth = isEthiopic(ch);
    const last = runs[runs.length - 1];
    if (last && (last.eth === eth || /\s/.test(ch))) last.s += ch;
    else runs.push({ eth, s: ch });
  }
  if (runs.length === 0) return;
  runs.forEach((r, i) => {
    const isLast = i === runs.length - 1;
    doc.font(r.eth ? pick.eth : pick.latin).text(r.s, {
      continued: !isLast,
      // Non-final runs must not wrap; the FINAL segment omits lineBreak so
      // pdfkit completes the line and the cursor wraps to the next one
      // (keeping lineBreak:false there leaves the cursor mid-line).
      ...(!isLast ? { lineBreak: false } : {}),
    });
  });
}

// ── Palette ──────────────────────────────────────────────────────────────────

/** Render a (mostly single-script) label at explicit coordinates, picking the
 *  font by script so Amharic labels never hit the Latin-only font. */
function label(
  doc: PDFKit.PDFDocument,
  str: string,
  x: number,
  y: number,
  opts: PDFKit.Mixins.TextOptions & { bold?: boolean; size?: number; color?: string } = {}
) {
  const { bold = true, size, color, ...textOpts } = opts;
  const eth = isEthiopic(str);
  doc.font(bold ? (eth ? F.ethiopic.bold : F.latin.bold) : eth ? F.ethiopic.regular : F.latin.regular);
  if (size) doc.fontSize(size);
  if (color) doc.fillColor(color);
  return doc.text(str, x, y, textOpts);
}

