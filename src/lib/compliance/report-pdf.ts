// @types/pdfkit misses two runtime-valid members (the chained `arc()` path
// mixin and the internal buffered-pages array) — typed accessors for them:
type ArcCapable = PDFKit.PDFDocument & {
  arc(x: number, y: number, radius: number, startAngle: number, endAngle: number, anticlockwise?: boolean): PDFKit.PDFDocument;
};
const arcOf = (doc: PDFKit.PDFDocument) => doc as ArcCapable;
const pageBufferOf = (doc: PDFKit.PDFDocument) =>
  (doc as PDFKit.PDFDocument & { _pageBuffer: unknown[] })._pageBuffer;

