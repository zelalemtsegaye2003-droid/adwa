function scoreColorHex(score: number) {
  return score >= 75 ? C.green : score >= 50 ? C.amber : C.red;
}
function severityColor(sev: string) {
  return sev === "critical" ? C.red : sev === "high" ? C.amber : C.yellow;
}
function slaColor(state: string) {
  switch (state) {
    case "OVERDUE": return C.red;
    case "DUE_SOON": return C.amber;
    case "ON_TRACK":
    case "CLOSED_ON_TIME": return C.green;
    case "CLOSED_LATE": return C.orange;
    default: return C.muted;
  }
}

